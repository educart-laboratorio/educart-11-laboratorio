import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const m=JSON.parse(readFileSync('public/images/educart-gestao.webmanifest','utf8'));
const admin=readFileSync('src/app/admin/layout.tsx','utf8');
const policy=readFileSync('src/lib/security/preview-native-policy.ts','utf8');
