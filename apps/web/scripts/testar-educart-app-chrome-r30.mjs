assert.equal(m.start_url,'/admin');
assert.equal(m.scope,'/admin');
assert.equal(m.display,'standalone');
assert.equal(m.id,'/admin');
assert(m.icons.some(x=>x.type==='image/svg+xml'&&x.src==='/images/oficina-atores-simbolo.svg'));
assert(admin.includes("manifest: '/images/educart-gestao.webmanifest'"));
assert(admin.includes('robots:')&&admin.includes('index: false'));
assert(policy.includes("pathname.startsWith('/images/')"));
assert(policy.includes("if (pathname === '/admin/login'"));
assert(!policy.includes("pathname.startsWith('/admin/') return 'publico'"));
assert(supabase.includes('createBrowserClient'));
assert(supabase.includes('NEXT_PUBLIC_SUPABASE_URL'));
assert(ui.includes("supabase.from('inscricoes_oficina')"));
assert(ui.includes("supabase.rpc('educart_matricular_simples_dev'"));
assert(ui.includes("supabase.rpc('educart_definir_pagamento_simples_dev'"));
assert(!/localStorage\.(setItem|getItem)|JSON\.parse\(localStorage/.test(ui));
