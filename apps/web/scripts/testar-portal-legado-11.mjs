import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {lerRolCsv,ROL_FICTICIO_DEV} from '../src/lib/rol-importacao-dev.ts';

const linhas=lerRolCsv(ROL_FICTICIO_DEV);
assert.equal(linhas.length,2);
assert.equal(linhas[0].nome_completo,'Lia Exemplo');
assert.equal(linhas[0].email,'lia-exemplo@example.invalid');
assert.equal(linhas[1].data_nascimento,'2001-02-12');
assert.equal(linhas[0].telefone,'71900000001');
const comAspas=lerRolCsv('\uFEFFsep=;\r\nreferencia;nome_completo;email;telefone;data_nascimento\r\n"ROL;3";"Ana ""Teste""";ana@example.invalid;71999990001;2000-09-10\r\n');
assert.equal(comAspas[0].referencia,'ROL;3');
assert.equal(comAspas[0].nome_completo,'Ana "Teste"');
assert.throws(()=>lerRolCsv('referencia;nome_completo;email;telefone;data_nascimento\nA;N;invalid;123;2026-99-99'),/inválid/);
assert.throws(()=>lerRolCsv('referencia;nome_completo;email;telefone;data_nascimento\nA-1;Lia Exemplo;lia@example.invalid;71900000001;2000-01-01\nA-1;Nina Exemplo;nina@example.invalid;71900000002;2000-01-01'),/duplicidade/);
assert.throws(()=>lerRolCsv('referencia;nome_completo;email;telefone;data_nascimento\nA-1;"Lia Exemplo;lia@example.invalid;71900000001;2000-01-01'),/aspas/);
const admin=readFileSync('src/app/admin/page.tsx','utf8');
const aluno=readFileSync('src/app/minha-educart/page.tsx','utf8');
const login=readFileSync('src/app/minha-educart/login/page.tsx','utf8');
const sql=readFileSync('../../supabase/security-review/EDUCART_11_DEV_IMPORTACAO_LEGADO_AUDITADA_20261104.sql','utf8');
const sqlAluno=readFileSync('../../supabase/security-review/EDUCART_11_DEV_PORTAL_ESTUDANTE_VINCULO_FOTO_20261104.sql','utf8');
assert.doesNotMatch(admin, /<AdminVinculosDev/, 'Sem pedido manual na navegação 1.2');
assert.doesNotMatch(admin, /<AdminImportacaoLegadoDev/, 'Sem importação CSV na navegação 1.2');
assert.match(sql, /ENABLE ROW LEVEL SECURITY/i);
assert.match(sqlAluno, /ENABLE ROW LEVEL SECURITY/i);
assert.match(aluno, /educart_solicitacoes_vinculo_dev/, 'Revisão histórica preservada');
assert.doesNotMatch(aluno, /onSubmit=\{solicitarVinculo\}/, 'Aluno recebe convite de matrícula');
assert.match(aluno, /educart_fotos_consentimento_dev/);
assert.match(aluno, /createSignedUrl/);
assert.match(aluno, /image\/jpeg/);
assert.match(aluno, /image\/webp/);
assert.match(aluno, /5\*1024\*1024/);
assert.match(login, /signInWithPassword/);
assert.match(login, /signUp/);
assert.match(readFileSync('../../supabase/security-review/EDUCART_11_DEV_REPARO_ORIGEM_RECADASTRAMENTO_20261104.sql','utf8'), /'recadastramento','pendente'/);
assert.doesNotMatch(sql, /insert into public\.mensalidades_formacao|status='pago'|set situacao='ativa'/i);
assert.match(sqlAluno, /file_size_limit,allowed_mime_types/);
assert.match(sqlAluno, /5242880,ARRAY\['image\/jpeg','image\/webp'\]/);
assert.match(sqlAluno, /ENABLE ROW LEVEL SECURITY/);
assert.doesNotMatch(sqlAluno, /public\s*=\s*true|service_role/i);
console.log('OK: Minha EducART, foto privada com consentimento, vinculo humano e importacao CSV auditada sem gerar divida.');
