assert(!/private static final String KEY="(?:sb_secret_|eyJ)/.test(api), 'Nunca embutir chave secreta ou legacy token');
assert(api.includes('/auth/v1/user')&&api.includes('portal_admins')&&api.includes('equipe_papeis'));
assert(api.includes('educart_r12_vincular_estudante_turma_dev')&&api.includes('p_tipo_vinculo","novo_pendente"'));
