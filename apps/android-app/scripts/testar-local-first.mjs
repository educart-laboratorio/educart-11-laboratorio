import assert from 'node:assert/strict';
import fs from 'node:fs';
const prefix='apps/android-app/';
const main=fs.readFileSync(prefix+'app/src/main/java/pro/educart/gestao/MainActivity.java','utf8');
const web=fs.readFileSync(prefix+'app/src/main/java/pro/educart/gestao/GestaoOnlineActivity.java','utf8');
